function parseFrontmatter(content) {
  const match = content.match(/^---\s*\r?\n([\s\S]*?)\r?\n---\s*\r?\n([\s\S]*)$/);
  if (!match) return { meta: {}, body: content };
  const yaml = match[1];
  const body = match[2];
  const meta = {};
  const lines = yaml.split(/\r?\n/);
  let currentKey = null;
  let buf = [];
  let inMultiline = false;
  for (const line of lines) {
    if (inMultiline) {
      if (/^\s+/.test(line) || line === '') {
        buf.push(line.replace(/^\s{2}/, ''));
        continue;
      } else {
        meta[currentKey] = buf.join('\n').trim();
        inMultiline = false;
      }
    }
    const m = line.match(/^(\w[\w-]*):\s*(.*)$/);
    if (m) {
      currentKey = m[1];
      if (m[2] === '|' || m[2] === '>') {
        inMultiline = true;
        buf = [];
      } else {
        meta[currentKey] = m[2].replace(/^["']|["']$/g, '');
      }
    }
  }
  if (inMultiline && currentKey) meta[currentKey] = buf.join('\n').trim();
  return { meta, body };
}

const dirs = readdirSync(SKILLS_DIR).filter(d => statSync(join(SKILLS_DIR, d)).isDirectory());
const skills = {};
let totalBytes = 0;

for (const name of dirs) {
  const skillPath = join(SKILLS_DIR, name, 'SKILL.md');
  let raw;
  try { raw = readFileSync(skillPath, 'utf-8'); }
  catch { console.warn('SKIP no SKILL.md:', name); continue; }
  const { meta, body } = parseFrontmatter(raw);
  const knowledgeFiles = KNOWLEDGE_MAP[name] || [];
  const knowledge = knowledgeFiles.map(f => ({
    name: f,
    content: readFileSync(join(KNOWLEDGE_DIR, f), 'utf-8'),
  }));
  const display = SKILL_META[name] || { group: '其他', icon: '•', label: name };
  skills[name] = {
    name,
    label: display.label,
    icon: display.icon,
    group: display.group,
    description: meta.description || '',
    body,
    knowledge,
  };
  totalBytes += body.length + knowledge.reduce((s, k) => s + k.content.length, 0);
}

let dictionary = '';
try { dictionary = readFileSync(DICTIONARY_FILE, 'utf-8'); }
catch { console.warn('SKIP 高频概念词典.md not found'); }

const payload = `// Auto-generated by build.mjs — do not edit by hand.
window.DBS_SKILLS = ${JSON.stringify(skills)};
window.DBS_GROUPS = ${JSON.stringify(['主入口', '诊断', '状态', '基建', '聊天室'])};
window.DBS_DICTIONARY = ${JSON.stringify(dictionary)};
`;

writeFileSync(OUT, payload, 'utf-8');
console.log(`Wrote ${OUT}`);
